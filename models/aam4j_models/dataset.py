"""The 3->4 join: metric profiles + labels -> a model-ready table.

Three rules from `docs/05-labels-and-datasets.md` and `docs/01-pipeline.md` are
enforced here rather than left to whoever writes the training script.

**1. Never split randomly by row.** `leave_one_system_out` is the only splitter
this module offers. Two variants of the same system share almost all of their
structure, so a random split lets a model memorise the service and report an
accuracy that will not survive a reviewer.

**2. Undetermined is not zero.** A metric that could not be computed becomes
the median of the *training* fold plus an explicit `<metric>__undetermined`
indicator column. The indicator is itself architectural: it says "evidence for
this metric is missing on this element", which is a fact about the element, so
it satisfies the feature-membership rule of `models/README.md`. Imputing from
the whole dataset instead of the training fold would leak the test systems'
distribution into training, so the statistics are fitted per fold.

**3. The detector of an injected property is not a feature for that task.**
Mutation labels are generated by an operator, and the deterministic metric that
detects that same property would predict it perfectly and prove nothing. The
exclusions are declared in `EXCLUDED_FEATURES`, travel into the run record, and
are the difference between measuring a model and measuring a tautology.
"""

from __future__ import annotations

import csv
import os
from dataclasses import asdict, dataclass

from aam4j_models.mutate import CYCLE, OVERSIZED_SERVICE, SHARED_PERSISTENCE

#: Per task, the features that would make the task circular. See rule 3 above.
EXCLUDED_FEATURES: dict[str, tuple[str, ...]] = {
    CYCLE: ("CYC",),
    SHARED_PERSISTENCE: ("SHARED_DB",),
    OVERSIZED_SERVICE: ("GOD",),
}

#: `SCF` is system-level; it is not a property of the service being classified.
NON_SERVICE_METRICS = ("SCF",)

LABEL_COLUMNS = [
    "system",
    "snapshot",
    "variant",
    "element_id",
    "task",
    "label",
    "label_provenance",
    "operator",
    "note",
]


@dataclass(frozen=True)
class Label:
    system: str
    snapshot: str
    variant: str
    element_id: str
    task: str
    label: int
    label_provenance: str
    operator: str
    note: str


def write_labels(labels: list[Label], path: str) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    rows = sorted((asdict(label) for label in labels), key=lambda r: (r["task"], r["variant"], r["element_id"]))
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        writer = csv.DictWriter(handle, fieldnames=LABEL_COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return path


def read_labels(path: str) -> list[Label]:
    with open(path, encoding="utf-8") as handle:
        return [Label(**{**row, "label": int(row["label"])}) for row in csv.DictReader(handle)]


def wide(profile_rows: list[dict]) -> dict[str, dict[str, tuple[float | None, bool]]]:
    """Long metric profile -> `{element_id: {metric: (value, determined)}}`.

    Service-level metrics only: a system-level metric is the same number for
    every row of that system and would act as a system identifier, which is the
    leak `leave_one_system_out` exists to prevent.
    """
    table: dict[str, dict[str, tuple[float | None, bool]]] = {}
    for row in profile_rows:
        if row["element_kind"] != "service":
            continue
        determined = row["determined"] in (True, "true")
        raw = row["value"]
        value = float(raw) if determined and raw not in ("", None) else None
        table.setdefault(row["element_id"], {})[row["metric"]] = (value, determined)
    return table


@dataclass(frozen=True)
class Dataset:
    task: str
    feature_names: tuple[str, ...]
    rows: tuple[dict, ...]
    excluded: tuple[str, ...]

    @property
    def systems(self) -> tuple[str, ...]:
        return tuple(sorted({row["system"] for row in self.rows}))

    def positives(self) -> int:
        return sum(1 for row in self.rows if row["label"] == 1)


def assemble(
    profiles: dict[tuple[str, str], list[dict]],
    labels: list[Label],
    task: str,
) -> Dataset:
    """One dataset for `task`. `profiles` is keyed by `(system, variant)`."""
    wide_by_variant = {key: wide(rows) for key, rows in profiles.items()}

    metrics: set[str] = set()
    for table in wide_by_variant.values():
        for cells in table.values():
            metrics.update(cells)
    excluded = tuple(sorted(set(EXCLUDED_FEATURES.get(task, ())) | set(NON_SERVICE_METRICS)))
    feature_names = tuple(sorted(metrics - set(excluded)))

    rows: list[dict] = []
    for label in labels:
        if label.task != task:
            continue
        table = wide_by_variant.get((label.system, label.variant))
        if table is None or label.element_id not in table:
            continue
        cells = table[label.element_id]
        row = {
            "system": label.system,
            "variant": label.variant,
            "element_id": label.element_id,
            "label": label.label,
            "operator": label.operator,
        }
        for name in feature_names:
            value, determined = cells.get(name, (None, False))
            row[name] = value if determined else None
        rows.append(row)
    rows.sort(key=lambda r: (r["system"], r["variant"], r["element_id"]))
    return Dataset(task=task, feature_names=feature_names, rows=tuple(rows), excluded=excluded)


def leave_one_system_out(dataset: Dataset) -> list[tuple[str, list[int], list[int]]]:
    """`(held_out_system, train_indices, test_indices)` per fold.

    The headline number of `models/README.md`. Folds with no positive example
    in the test set are still returned: hiding them would flatter the average,
    and a task that cannot be evaluated on a system is a finding about the
    label source, not a fold to drop quietly.
    """
    folds = []
    for system in dataset.systems:
        train = [i for i, row in enumerate(dataset.rows) if row["system"] != system]
        test = [i for i, row in enumerate(dataset.rows) if row["system"] == system]
        if train and test:
            folds.append((system, train, test))
    return folds


def materialise(dataset: Dataset, train: list[int], test: list[int]) -> dict:
    """Impute and add indicators, with statistics fitted on the training fold only."""
    medians: dict[str, float] = {}
    for name in dataset.feature_names:
        observed = sorted(
            dataset.rows[i][name] for i in train if dataset.rows[i][name] is not None
        )
        medians[name] = observed[len(observed) // 2] if observed else 0.0

    columns = list(dataset.feature_names) + [f"{name}__undetermined" for name in dataset.feature_names]

    def vector(index: int) -> list[float]:
        row = dataset.rows[index]
        values = [row[name] if row[name] is not None else medians[name] for name in dataset.feature_names]
        flags = [0.0 if row[name] is not None else 1.0 for name in dataset.feature_names]
        return [float(v) for v in values] + flags

    return {
        "columns": columns,
        "x_train": [vector(i) for i in train],
        "y_train": [dataset.rows[i]["label"] for i in train],
        "x_test": [vector(i) for i in test],
        "y_test": [dataset.rows[i]["label"] for i in test],
        "test_elements": [dataset.rows[i]["element_id"] for i in test],
        "medians": medians,
    }


def write_dataset(dataset: Dataset, path: str) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    columns = ["system", "variant", "element_id", "operator", "label", *dataset.feature_names]
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, lineterminator="\n")
        writer.writeheader()
        for row in dataset.rows:
            writer.writerow({column: ("" if row.get(column) is None else row.get(column)) for column in columns})
    return path
